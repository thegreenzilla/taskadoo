create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid() and active
$$;

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() in ('admin','dispatcher'), false)
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() = 'admin', false)
$$;

create or replace function public.my_name() returns text
language sql stable security definer set search_path = public as $$
  select coalesce(nullif(full_name,''), email, '') from public.profiles where id = auth.uid()
$$;

create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at := now(); return new; end $$;

drop trigger if exists jobs_touch on public.jobs;
create trigger jobs_touch before update on public.jobs
  for each row execute function public.touch_updated_at();

-- New sign-up → profile. The very first account becomes Admin.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  req text := coalesce(m->>'requested_role', '');
begin
  if req not in ('assembler','enterprise') then req := ''; end if;
  insert into public.profiles (id, email, full_name, mobile, company, requested_role, role)
  values (new.id, coalesce(new.email,''), left(coalesce(m->>'full_name',''),120),
          left(coalesce(m->>'mobile',''),40), left(coalesce(m->>'company',''),120), req,
          case when not exists (select 1 from public.profiles where role = 'admin') then 'admin' else 'customer' end)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Only Admin may change role / active / email; nobody can change their own role.
create or replace function public.guard_profile() returns trigger
language plpgsql set search_path = public as $$
begin
  -- SQL Editor / service connections are not limited
  if current_user not in ('anon','authenticated') then return new; end if;
  if not public.is_admin() or new.id = auth.uid() then
    new.role := old.role;
    new.active := old.active;
    new.email := old.email;
    if not public.is_admin() then new.requested_role := old.requested_role; end if;
  end if;
  new.id := old.id;
  new.created_at := old.created_at;
  return new;
end $$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard before update on public.profiles
  for each row execute function public.guard_profile();

