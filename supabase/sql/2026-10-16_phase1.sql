create or replace function public.job_file_access(p_name text, p_write boolean) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare jid bigint; j public.jobs;
begin
  if split_part(p_name, '/', 1) !~ '^\d{1,18}$' then return false; end if;
  jid := split_part(p_name, '/', 1)::bigint;
  select * into j from public.jobs where id = jid;
  if not found then return false; end if;
  if p_write then
    return public.my_role() = 'assembler' and (j.lead_id = auth.uid() or j.helper_id = auth.uid())
      and j.status in ('arrived','in_progress','finished');
  end if;
  return public.is_staff() or j.customer_id = auth.uid() or j.lead_id = auth.uid() or j.helper_id = auth.uid();
end $$;
grant execute on function public.job_file_access(text, boolean) to authenticated;

