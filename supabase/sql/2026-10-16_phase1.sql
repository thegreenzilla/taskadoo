create extension if not exists pgcrypto;

-- ───────────────────────── Tables ─────────────────────────

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  full_name text not null default '',
  mobile text not null default '',
  role text not null default 'customer'
    check (role in ('customer','assembler','dispatcher','enterprise','admin')),
  requested_role text not null default ''
    check (requested_role in ('','assembler','enterprise')),
  company text not null default '',
  area text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.catalog (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  brand text not null,
  cat text not null,
  name text not null,
  fee numeric(10,2) not null check (fee >= 0),
  crew int not null default 1 check (crew between 1 and 4),
  minutes int not null default 60 check (minutes between 5 and 1440),
  emoji text not null default '📦',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  code text unique,
  source text not null default 'customer' check (source in ('customer','enterprise','staff')),
  customer_id uuid references public.profiles(id) on delete set null,
  company text not null default '',
  customer_name text not null,
  mobile text not null,
  address text not null,
  area text not null default '',
  job_date date not null,
  slot text not null,
  notes text not null default '',
  items jsonb not null default '[]'::jsonb,
  crew int not null default 1,
  total numeric(10,2) not null default 0,
  commission_pct numeric(5,2) not null default 22,
  lead_pct numeric(5,2) not null default 55,
  status text not null default 'new'
    check (status in ('new','assigned','accepted','travelling','arrived','in_progress','finished','done','cancelled')),
  lead_id uuid references public.profiles(id) on delete set null,
  helper_id uuid references public.profiles(id) on delete set null,
  lead_name text not null default '',
  helper_name text not null default '',
  lead_ok boolean not null default false,
  helper_ok boolean not null default false,
  started_at timestamptz,
  finished_at timestamptz,
  completed_at timestamptz,
  photos jsonb not null default '[]'::jsonb,
  signature text,
  signed_name text not null default '',
  paid boolean not null default false,
  paid_at timestamptz,
  events jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists jobs_status_idx on public.jobs(status);
create index if not exists jobs_date_idx on public.jobs(job_date);
create index if not exists jobs_customer_idx on public.jobs(customer_id);
create index if not exists jobs_lead_idx on public.jobs(lead_id);
create index if not exists jobs_helper_idx on public.jobs(helper_id);

