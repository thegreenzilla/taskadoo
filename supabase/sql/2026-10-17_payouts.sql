-- Taskadoo – v1.5: weekly assembler payouts (every Monday, by GCash). Taskadoo pays any transfer fee.
-- Paste the whole file into Supabase → SQL Editor → Run. Safe to run more than once. Run AFTER the earlier files.

-- GCash details on the assembler's profile (copied from the application when they pass; editable in Profile)
alter table public.profiles add column if not exists gcash_name text not null default '';
alter table public.profiles add column if not exists gcash_number text not null default '';
grant update (gcash_name, gcash_number) on public.profiles to authenticated;
update public.profiles p set gcash_name = coalesce(a.data->>'gcash_name',''), gcash_number = coalesce(a.data->>'gcash_number','')
  from public.applications a where a.user_id = p.id and p.gcash_number = '' and a.data ? 'gcash_number';

-- ───────────────────────── Tables ─────────────────────────
create table if not exists public.payouts (
  id bigint generated by default as identity primary key,
  assembler_id uuid not null references public.profiles(id),
  assembler_name text not null default '',
  period_end date not null,                       -- jobs ready by the end of this day (Manila) – normally a Sunday
  amount numeric(12,2) not null default 0,
  gcash_name text not null default '',
  gcash_number text not null default '',
  status text not null default 'pending' check (status in ('pending','sent','cancelled')),
  reference text not null default '',
  sent_at timestamptz, sent_by uuid, sent_by_name text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.payout_lines (
  id bigint generated by default as identity primary key,
  payout_id bigint not null references public.payouts(id) on delete cascade,
  job_id bigint not null references public.jobs(id),
  assembler_id uuid not null,
  share_role text not null check (share_role in ('lead','helper')),
  amount numeric(12,2) not null,
  unique (job_id, assembler_id)                  -- a job's share is never paid twice
);
create index if not exists payout_lines_payout_idx on public.payout_lines(payout_id);

alter table public.payouts enable row level security;
alter table public.payout_lines enable row level security;
drop policy if exists payouts_read on public.payouts;
create policy payouts_read on public.payouts for select to authenticated using (assembler_id = auth.uid() or public.is_admin());
drop policy if exists payout_lines_read on public.payout_lines;
create policy payout_lines_read on public.payout_lines for select to authenticated using (assembler_id = auth.uid() or public.is_admin());
grant select on public.payouts, public.payout_lines to authenticated;

-- ───────────────────────── Shares ─────────────────────────
-- Each assembler's share of a closed job (same split as the app: commission off the top, lead % of the pool on team jobs)
create or replace function public.job_shares(j public.jobs) returns table (assembler_id uuid, share_role text, amount numeric)
language sql stable as $$
  with x as (
    select public.job_due(j) as due,
           (j.helper_id is not null or j.crew > 1) as two
  ), y as (
    select due - due * j.commission_pct / 100 as pool, two from x
  )
  select j.lead_id, 'lead', round(case when two then pool * j.lead_pct / 100 else pool end, 2) from y where j.lead_id is not null
  union all
  select j.helper_id, 'helper', round(pool - pool * j.lead_pct / 100, 2) from y where j.helper_id is not null
$$;

-- Shares that are ready to pay by the end of p_end (Manila): closed, past the problem window, no open dispute,
-- paid by the customer (business bookings are billed monthly, so they don't wait), and not in a payout yet.
create or replace function public.payout_ready(p_end date) returns table (
  assembler_id uuid, assembler_name text, gcash_name text, gcash_number text, job_id bigint, code text, share_role text, amount numeric, completed_at timestamptz)
language sql stable security definer set search_path = public as $$
  select s.assembler_id, coalesce(nullif(p.full_name,''), p.email), p.gcash_name, p.gcash_number, j.id, j.code, s.share_role, s.amount, j.completed_at
  from public.jobs j
  cross join lateral public.job_shares(j) s
  join public.profiles p on p.id = s.assembler_id
  where public.is_admin()
    and j.status in ('done','failed_visit') and j.dispute <> 'open'
    and (j.paid or j.source = 'enterprise')
    and j.completed_at + make_interval(hours => j.dispute_hours) <= ((p_end + 1)::timestamp at time zone 'Asia/Manila')
    and s.amount > 0
    and not exists (select 1 from public.payout_lines l join public.payouts po on po.id = l.payout_id
                    where l.job_id = j.id and l.assembler_id = s.assembler_id and po.status <> 'cancelled')
  order by 2, j.completed_at
$$;

-- Create this week's payout list: one pending payout per assembler
create or replace function public.payout_create(p_end date) returns int
language plpgsql security definer set search_path = public as $$
declare r record; pid bigint; n int := 0;
begin
  if not public.is_admin() then raise exception 'Only Admin can create payouts.'; end if;
  if p_end > (now() at time zone 'Asia/Manila')::date then raise exception 'Pick a day that has already started (normally last Sunday).'; end if;
  -- shares of cancelled payouts can be paid again
  delete from public.payout_lines l using public.payouts po where po.id = l.payout_id and po.status = 'cancelled';
  for r in select assembler_id, min(assembler_name) nm, min(gcash_name) gn, min(gcash_number) gnum, sum(amount) total
           from public.payout_ready(p_end) group by assembler_id loop
    insert into public.payouts (assembler_id, assembler_name, period_end, amount, gcash_name, gcash_number)
      values (r.assembler_id, r.nm, p_end, r.total, coalesce(r.gn,''), coalesce(r.gnum,'')) returning id into pid;
    insert into public.payout_lines (payout_id, job_id, assembler_id, share_role, amount)
      select pid, job_id, assembler_id, share_role, amount from public.payout_ready(p_end) where assembler_id = r.assembler_id;
    n := n + 1;
  end loop;
  return n;
end $$;

create or replace function public.payout_mark_sent(p_id bigint, p_reference text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only Admin can record payouts.'; end if;
  if length(trim(coalesce(p_reference,''))) < 4 then raise exception 'Type the GCash reference number.'; end if;
  update public.payouts set status = 'sent', reference = left(trim(p_reference),60), sent_at = now(), sent_by = auth.uid(),
    sent_by_name = coalesce(public.my_name(),'') where id = p_id and status = 'pending';
  if not found then raise exception 'This payout is not waiting to be sent.'; end if;
end $$;

create or replace function public.payout_cancel(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only Admin can cancel payouts.'; end if;
  update public.payouts set status = 'cancelled' where id = p_id and status = 'pending';
  if not found then raise exception 'Only payouts that have not been sent can be cancelled.'; end if;
  delete from public.payout_lines where payout_id = p_id;   -- the jobs become ready again
end $$;

-- Passing the evaluation copies the GCash details to the profile
create or replace function public.copy_gcash_on_pass() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'passed' and old.status is distinct from 'passed' then
    update public.profiles set gcash_name = coalesce(new.data->>'gcash_name', gcash_name), gcash_number = coalesce(new.data->>'gcash_number', gcash_number)
      where id = new.user_id;
  end if;
  return new;
end $$;
drop trigger if exists applications_gcash on public.applications;
create trigger applications_gcash after update on public.applications for each row execute function public.copy_gcash_on_pass();

revoke all on function public.payout_ready(date), public.payout_create(date), public.payout_mark_sent(bigint,text), public.payout_cancel(bigint) from public, anon;
grant execute on function public.payout_ready(date), public.payout_create(date), public.payout_mark_sent(bigint,text), public.payout_cancel(bigint),
  public.job_shares(public.jobs) to authenticated;
