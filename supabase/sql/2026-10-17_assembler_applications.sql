-- ───────────────────────── Tables ─────────────────────────
create table if not exists public.eval_slots (
  id bigint generated by default as identity primary key,
  hub text not null,
  starts_at timestamptz not null,
  seats int not null default 4 check (seats between 1 and 50),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists eval_slots_start_idx on public.eval_slots(starts_at);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  status text not null default 'draft' check (status in ('draft','booked','passed','failed','no_show')),
  data jsonb not null default '{}'::jsonb,      -- birth_date, base_area, travel_km, years, brands[], skills[], commitment, mober, employee_id, gcash_name, gcash_number
  docs jsonb not null default '{}'::jsonb,      -- id / nbi / med: {path, at, ok (null|true|false), note}
  emp_verified boolean,                          -- Mober employee ID confirmed by an evaluator
  slot_id bigint references public.eval_slots(id),
  moved int not null default 0,
  score jsonb not null default '{}'::jsonb,
  result_note text not null default '',
  evaluated_by uuid, evaluator_name text not null default '', evaluated_at timestamptz,
  events jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists applications_slot_idx on public.applications(slot_id);
drop trigger if exists applications_touch on public.applications;
create trigger applications_touch before update on public.applications for each row execute function public.touch_updated_at();

alter table public.eval_slots enable row level security;
alter table public.applications enable row level security;

drop policy if exists slots_read on public.eval_slots;
