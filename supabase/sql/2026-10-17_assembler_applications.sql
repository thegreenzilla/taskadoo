drop policy if exists slots_write on public.eval_slots;
create policy slots_write on public.eval_slots for all to authenticated using (public.is_evaluator()) with check (public.is_evaluator());
drop policy if exists apps_read on public.applications;
create policy apps_read on public.applications for select to authenticated using (user_id = auth.uid() or public.is_evaluator());
