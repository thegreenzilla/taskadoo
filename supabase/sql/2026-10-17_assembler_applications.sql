-- ───────────────────────── Helpers ─────────────────────────
create or replace function public.slot_booked(p_slot bigint) returns int
language sql stable security definer set search_path = public as $$
  select count(*)::int from public.applications where slot_id = p_slot and status = 'booked'
$$;

-- one application with the person's name and the slot, as JSON
create or replace function public.app_row(a public.applications) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(a) || jsonb_build_object(
    'full_name', p.full_name, 'email', p.email, 'mobile', p.mobile, 'role', p.role,
    'slot_at', s.starts_at, 'slot_hub', s.hub)
  from public.profiles p left join public.eval_slots s on s.id = a.slot_id where p.id = a.user_id
$$;

-- ───────────────────────── Applicant ─────────────────────────
create or replace function public.app_me() returns jsonb
language sql stable security definer set search_path = public as $$
  select public.app_row(a) from public.applications a where a.user_id = auth.uid()
$$;

-- Save the form (steps 1 and 3, and the Mober / GCash fields). Can be called again while not yet evaluated.
create or replace function public.app_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  me uuid := auth.uid(); r text := public.my_role(); a public.applications; d jsonb := '{}'::jsonb; bd date;
  cfg jsonb := coalesce((select value from public.settings where key = 'main'), '{}'::jsonb);
  min_age int := coalesce((cfg->>'min_age')::int, 21); had boolean;
begin
  if r is null then raise exception 'Please sign in first.'; end if;
  if r <> 'customer' then raise exception 'This account is already % – no application needed.', r; end if;
  select * into a from public.applications where user_id = me for update;
  had := found;
  if had and a.status in ('passed','failed') then raise exception 'Your application has already been decided.'; end if;
  p := coalesce(p, '{}'::jsonb);
  if p ? 'birth_date' and coalesce(p->>'birth_date','') <> '' then
    begin bd := (p->>'birth_date')::date; exception when others then raise exception 'Please enter your birth date.'; end;
    if bd > (now() at time zone 'Asia/Manila')::date - make_interval(years => min_age) then
      raise exception 'You must be at least % years old to work as an assembler.', min_age; end if;
    if bd < date '1940-01-01' then raise exception 'Please check your birth date.'; end if;
  end if;
  -- keep only known fields
  d := jsonb_strip_nulls(jsonb_build_object(
    'birth_date', nullif(p->>'birth_date',''), 'base_area', left(nullif(p->>'base_area',''),80),
    'travel_km', case when p ? 'travel_km' then least(greatest(coalesce((p->>'travel_km')::int,0),0),100) end,
    'years', left(nullif(p->>'years',''),20), 'commitment', case when p->>'commitment' in ('Full-time','Part-time') then p->>'commitment' end,
    'brands', case when jsonb_typeof(p->'brands') = 'array' then p->'brands' end,
    'skills', case when jsonb_typeof(p->'skills') = 'array' then p->'skills' end,
    'mober', case when p ? 'mober' then (p->>'mober')::boolean end, 'employee_id', left(nullif(trim(p->>'employee_id'),''),40),
    'gcash_name', left(nullif(trim(p->>'gcash_name'),''),120), 'gcash_number', left(nullif(regexp_replace(coalesce(p->>'gcash_number',''),'[^0-9+]','','g'),''),20)));
  if p ? 'mober' and not coalesce((p->>'mober')::boolean, false) then d := d || jsonb_build_object('employee_id', null); end if;
  if not had then
    insert into public.applications (user_id, data, events) values (me, jsonb_strip_nulls(d), public.add_event('[]'::jsonb, 'started'))
    returning * into a;
  else
    update public.applications set data = jsonb_strip_nulls(data || d),
      emp_verified = case when d ? 'employee_id' and d->>'employee_id' is distinct from data->>'employee_id' then null else emp_verified end
    where id = a.id returning * into a;
  end if;
  update public.profiles set requested_role = 'assembler',
    full_name = coalesce(nullif(left(trim(p->>'full_name'),120),''), full_name),
    mobile = coalesce(nullif(left(trim(p->>'mobile'),40),''), mobile),
    area = coalesce(a.data->>'base_area', area)
  where id = me;
  return public.app_row(a);
end $$;

-- Add or replace a document photo (id / nbi / med). The file is uploaded first to storage "apps/<user id>/…".
create or replace function public.app_doc(p_kind text, p_path text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications;
begin
  if p_kind not in ('id','nbi','med') then raise exception 'Unknown document.'; end if;
  if p_path !~ ('^' || auth.uid() || '/[A-Za-z0-9_-]+\.(jpg|jpeg|png|webp)$') then raise exception 'Bad file.'; end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'apps' and o.name = p_path) then raise exception 'The photo did not upload. Please try again.'; end if;
  select * into a from public.applications where user_id = auth.uid() for update;
  if not found then raise exception 'Fill in step 1 first.'; end if;
  if a.status in ('passed','failed') then raise exception 'Your application has already been decided.'; end if;
  update public.applications set docs = docs || jsonb_build_object(p_kind, jsonb_build_object('path', p_path, 'at', now(), 'ok', null, 'note', ''))
    where id = a.id returning * into a;
  return public.app_row(a);
end $$;

-- Evaluation slots the applicant can pick (with seats left)
create or replace function public.eval_slot_list() returns table (id bigint, hub text, starts_at timestamptz, seats int, booked int, active boolean)
language sql stable security definer set search_path = public as $$
  select s.id, s.hub, s.starts_at, s.seats, public.slot_booked(s.id), s.active from public.eval_slots s
  where (s.active and s.starts_at > now()) or (public.is_evaluator() and s.starts_at > now() - interval '60 days')
  order by s.starts_at
$$;

-- Book (or move, once) the evaluation. The application is only sent once a slot is booked.
create or replace function public.app_book(p_slot bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications; s public.eval_slots; old public.eval_slots; mober boolean; miss text[] := '{}';
begin
  select * into a from public.applications where user_id = auth.uid() for update;
  if not found then raise exception 'Fill in your application first.'; end if;
  if a.status not in ('draft','booked','no_show') then raise exception 'Your application has already been decided.'; end if;
  mober := coalesce((a.data->>'mober')::boolean, false);
  if a.data->>'birth_date' is null then miss := array_append(miss, 'birth date'); end if;
  if a.data->>'base_area' is null then miss := array_append(miss, 'base location'); end if;
  if a.data->>'commitment' is null then miss := array_append(miss, 'full-time or part-time'); end if;
  if a.data->>'gcash_number' is null or a.data->>'gcash_name' is null then miss := array_append(miss, 'GCash name and number'); end if;
  if mober and a.data->>'employee_id' is null then miss := array_append(miss, 'Mober employee ID'); end if;
  if not mober and not (a.docs ? 'id') then miss := array_append(miss, 'valid ID photo'); end if;
  if not mober and not (a.docs ? 'nbi') then miss := array_append(miss, 'NBI clearance photo'); end if;
  if not (a.docs ? 'med') then miss := array_append(miss, 'medical certificate photo'); end if;
  if array_length(miss, 1) > 0 then raise exception 'Still missing: %.', array_to_string(miss, ', '); end if;
  select * into s from public.eval_slots where id = p_slot for update;
  if not found or not s.active then raise exception 'That time is no longer available.'; end if;
  if s.starts_at < now() + interval '2 hours' then raise exception 'Please pick a time at least 2 hours from now.'; end if;
  if a.status = 'booked' and a.slot_id = p_slot then return public.app_row(a); end if;
  if public.slot_booked(p_slot) >= s.seats then raise exception 'That time is full. Please pick another.'; end if;
  if a.status = 'booked' then
    if a.moved >= 1 then raise exception 'You can move your evaluation only once. Please contact Taskadoo.'; end if;
    select * into old from public.eval_slots where id = a.slot_id;
    if found and old.starts_at < now() + interval '2 hours' then raise exception 'Your evaluation is in less than 2 hours – it can no longer be moved.'; end if;
    update public.applications set slot_id = p_slot, moved = moved + 1,
      events = public.add_event(events, 'moved', to_char(s.starts_at at time zone 'Asia/Manila', 'Mon DD, HH12:MI AM')) where id = a.id returning * into a;
  else
    update public.applications set slot_id = p_slot, status = 'booked',
      events = public.add_event(events, 'booked', to_char(s.starts_at at time zone 'Asia/Manila', 'Mon DD, HH12:MI AM')) where id = a.id returning * into a;
  end if;
  return public.app_row(a);
end $$;

create or replace function public.app_cancel() returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications;
begin
  select * into a from public.applications where user_id = auth.uid() for update;
  if not found or a.status <> 'booked' then raise exception 'You have no evaluation booked.'; end if;
  update public.applications set status = 'draft', slot_id = null, events = public.add_event(events, 'cancelled') where id = a.id returning * into a;
  return public.app_row(a);
end $$;

-- ───────────────────────── Evaluator ─────────────────────────
create or replace function public.app_list() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.app_row(a) order by a.created_at desc), '[]'::jsonb) from public.applications a where public.is_evaluator()
$$;

create or replace function public.app_doc_review(p_app uuid, p_kind text, p_ok boolean, p_note text default '') returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications;
begin
  if not public.is_evaluator() then raise exception 'Only evaluators can check documents.'; end if;
  select * into a from public.applications where id = p_app for update;
  if not found or not (a.docs ? p_kind) then raise exception 'Document not found.'; end if;
  if not p_ok and length(trim(coalesce(p_note,''))) < 3 then raise exception 'Say what is wrong so the applicant can fix it.'; end if;
  update public.applications set docs = jsonb_set(docs, array[p_kind], (docs->p_kind) || jsonb_build_object('ok', p_ok, 'note', left(trim(coalesce(p_note,'')),300))),
    events = public.add_event(events, case when p_ok then 'doc_ok' else 'doc_bad' end, p_kind || case when p_ok then '' else ' – ' || left(trim(p_note),200) end)
  where id = a.id returning * into a;
  return public.app_row(a);
end $$;

create or replace function public.app_emp_verify(p_app uuid, p_ok boolean) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications;
begin
  if not public.is_evaluator() then raise exception 'Only evaluators can confirm this.'; end if;
  update public.applications set emp_verified = p_ok, events = public.add_event(events, case when p_ok then 'emp_ok' else 'emp_bad' end, data->>'employee_id')
    where id = p_app returning * into a;
  if not found then raise exception 'Application not found.'; end if;
  return public.app_row(a);
end $$;

-- result: passed (becomes an Assembler), failed, no_show (can book again)
create or replace function public.app_decide(p_app uuid, p_result text, p_score jsonb default '{}'::jsonb, p_note text default '') returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.applications; mober boolean; k text;
begin
  if not public.is_evaluator() then raise exception 'Only evaluators can record results.'; end if;
  if p_result not in ('passed','failed','no_show') then raise exception 'Choose Pass, Fail or No-show.'; end if;
  select * into a from public.applications where id = p_app for update;
  if not found then raise exception 'Application not found.'; end if;
  if a.status <> 'booked' then raise exception 'Only booked evaluations can get a result.'; end if;
  mober := coalesce((a.data->>'mober')::boolean, false);
  if p_result = 'passed' then
    foreach k in array case when mober then array['med'] else array['id','nbi','med'] end loop
      if coalesce((a.docs->k->>'ok')::boolean, false) is not true then
        raise exception 'Check the documents first: % is not marked OK.', case k when 'id' then 'the valid ID' when 'nbi' then 'the NBI clearance' else 'the medical certificate' end;
      end if;
    end loop;
    if mober and a.emp_verified is not true then raise exception 'Confirm the Mober employee ID first.'; end if;
  end if;
  if p_result = 'failed' and length(trim(coalesce(p_note,''))) < 3 then raise exception 'Write a short note on why.'; end if;
  update public.applications set status = p_result, score = coalesce(p_score, '{}'::jsonb), result_note = left(trim(coalesce(p_note,'')),1000),
    evaluated_by = auth.uid(), evaluator_name = coalesce(public.my_name(), ''), evaluated_at = now(),
    slot_id = case when p_result = 'no_show' then null else slot_id end,
    events = public.add_event(events, p_result, left(trim(coalesce(p_note,'')),200))
  where id = a.id returning * into a;
  if p_result = 'passed' then
    update public.profiles set role = 'assembler', requested_role = '', area = coalesce(a.data->>'base_area', area) where id = a.user_id;
  end if;
  return public.app_row(a);
end $$;

